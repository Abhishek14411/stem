  function translate(text, language) {
    const source = String(text)
    if (language === 'en') return source
    const leading = source.match(/^\s*/)?.[0] ?? ''
    const trailing = source.match(/\s*$/)?.[0] ?? ''
    const content = source.slice(leading.length, source.length - trailing.length)
    if (!content) return source
    let translated = byEnglish[content]
    if (translated) return `${leading}${translated}${trailing}`
    for (const [pattern, render] of dynamicRules) {
      const match = pattern.exec(content)
      if (match) {
        translated = render(...match)
        return `${leading}${translated}${trailing}`
      }
    }
    translated = replacements.reduce((result, entry) => result.replace(entry.regex, (_, prefix) => `${prefix}${entry.hindi}`), content)
    return `${leading}${translated}${trailing}`
  }

